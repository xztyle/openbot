/** The skin tone modifiers by tone: 0 is no modifier, 1 is light and 5 is dark. */
export const SKIN_TONES = ["", "\u{1F3FB}", "\u{1F3FC}", "\u{1F3FD}", "\u{1F3FE}", "\u{1F3FF}"] as const;

const VARIATION_SELECTOR = "️";
const SKIN_TONE_MODIFIERS = /[\u{1F3FB}-\u{1F3FF}]/gu;

/**
 * The emoji with a skin tone. The modifier goes after the first code point, and replaces the
 * variation selector there: ✌️ becomes ✌🏽, 🧑‍💻 becomes 🧑🏽‍💻. An emoji without `s` and tone 0 stay as they are.
 */
export function withSkinTone(entry: EmojiEntry, tone: number): string {
  const modifier = SKIN_TONES[tone];
  if (!entry.s || !modifier) return entry.e;
  const first = String.fromCodePoint(entry.e.codePointAt(0) ?? 0);
  const rest = entry.e.slice(first.length);
  return first + modifier + (rest.startsWith(VARIATION_SELECTOR) ? rest.slice(VARIATION_SELECTOR.length) : rest);
}

interface SearchRow {
  readonly entry: EmojiEntry;
  readonly name: string;
  readonly words: readonly string[];
  readonly keys: readonly string[];
  /** The short code where the emoji has one: "+1" for 👍, "tada" for 🎉. */
  readonly code: string | undefined;
}

const WORD_BREAK = /[^\p{L}\p{N}+]+/u;

function words(text: string): string[] {
  return text
    .toLocaleLowerCase("en")
    .split(WORD_BREAK)
    .filter((word) => word.length > 0);
}

// Built on the first search or lookup, not at import: most views that import the picker never open it.
let searchRows: readonly SearchRow[] | undefined;
let byEmoji: ReadonlyMap<string, EmojiEntry> | undefined;

function rows(): readonly SearchRow[] {
  searchRows ??= EMOJI_CATEGORIES.flatMap((category) =>
    category.emoji.map((entry) => ({
      entry,
      name: entry.n.toLocaleLowerCase("en"),
      words: words(entry.n),
      keys: entry.k ? words(entry.k) : [],
      code: entry.k?.startsWith(":") ? entry.k.slice(1).split(" ")[0]?.replaceAll("_", " ") : undefined,
    })),
  );
  return searchRows;
}

/** The entry of an emoji, with or without a skin tone, such as an emoji from the recent list. */
export function findEmoji(emoji: string): EmojiEntry | undefined {
  byEmoji ??= new Map(rows().map((row) => [row.entry.e, row.entry]));
  return byEmoji.get(emoji) ?? byEmoji.get(emoji.replace(SKIN_TONE_MODIFIERS, ""));
}

/** How well one query word matches a row: lower is better, undefined is no match. */
function termScore(row: SearchRow, term: string): number | undefined {
  const wordIndex = row.words.findIndex((word) => word.startsWith(term));
  if (wordIndex === 0) return row.words[0] === term ? 0 : 1;
  if (wordIndex > 0) return row.words[wordIndex] === term ? 2 : 3;
  return row.keys.some((key) => key.startsWith(term)) ? 4 : undefined;
}

/**
 * The emoji whose name words or keywords start with every word of the query, best first: the whole
 * name or the short code, then the name start, then a later name word, then a keyword. Equal scores
 * keep the picker order. A leading colon and underscores are ignored, so `:thumbs_up` finds 👍.
 */
export function searchEmoji(query: string, limit = 200): EmojiEntry[] {
  const text = query
    .trim()
    .replace(/^:+|:+$/gu, "")
    .replaceAll("_", " ");
  const terms = words(text);
  if (terms.length === 0) return [];
  const whole = terms.join(" ");
  const scored: { entry: EmojiEntry; score: number; order: number }[] = [];
  rows().forEach((row, order) => {
    if (row.entry.e === query.trim()) {
      scored.push({ entry: row.entry, score: -2, order });
      return;
    }
    let score = 0;
    for (const term of terms) {
      const value = termScore(row, term);
      if (value === undefined) return;
      score += value;
    }
    if (row.name === whole || row.code === whole) score = -1;
    else if (row.name.startsWith(whole)) score -= 0.5;
    scored.push({ entry: row.entry, score, order });
  });
  scored.sort((a, b) => a.score - b.score || a.order - b.order);
  return scored.slice(0, limit).map((item) => item.entry);
}
